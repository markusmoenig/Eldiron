#!/usr/bin/env python3
"""Generate the Rust channel contract from schema/bsdf.json (Eldiron core-only copy)."""
from pathlib import Path
import json, re, subprocess
root=Path(__file__).resolve().parent.parent
fields=json.loads((root/'schema/bsdf.json').read_text())
# Stable texture field IDs match the schema index. Height and normal are geometry inputs.
text='//! Generated by scripts/generate-bsdf.py from schema/bsdf.json.\nuse crate::{Error,Result};\n#[derive(Debug,Clone,Copy,PartialEq,Eq,Hash)]\npub enum Channel {\n'+''.join(f'    {f["variant"]},\n' for f in fields)+'    Distance,\n}\nimpl Channel {\n'
text+='pub const SURFACE: &[Self] = &['+','.join('Self::'+f['variant'] for f in fields)+'];\n'
text+='pub fn parse(s:&str)->Result<Self>{match s{'+''.join(f'"{f["name"]}"=>Ok(Self::{f["variant"]}),' for f in fields)+'"distance"=>Ok(Self::Distance),_=>Err(Error(format!("Unknown material channel {s:?}")))}}\n'
text+='pub fn name(self)-> &\'static str {match self{'+''.join(f'Self::{f["variant"]}=>"{f["name"]}",' for f in fields)+'Self::Distance=>"distance"}}\n'
text+='pub fn default(self)-> &\'static [f32] {match self{'+''.join(f'Self::{f["variant"]}=>&['+','.join(str(float(v)) for v in f['default'])+'],' for f in fields)+'Self::Distance=>&[0.0]}}\n'
text+='pub fn width(self)->usize{self.default().len()}\n}\n'
catalog=[dict(name=f['name'],width=len(f['default']),default=f['default'],group=f['group'],field=i) for i,f in enumerate(fields)]
text+='pub fn catalog_json()->String{r#\''+json.dumps(catalog,separators=(',',':'))+'\'#.into()}\n'
text=text.replace("r#'",'r#"').replace("'#.",'"#.')
(root/'src/bsdf.rs').write_text(text)
subprocess.run(['rustfmt','--edition','2024',str(root/'src/bsdf.rs')],check=True)
