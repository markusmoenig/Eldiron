fn generate_vscode_package(definition: &LanguageDefinition) -> Result<String, String> {
    pretty_json(json!({
        "$generated": GENERATED_NOTICE,
        "name": "eldiron-recipe-language",
        "displayName": definition.name,
        "description": "Syntax highlighting for Eldiron procedural Recipe files.",
        "version": "0.0.1",
        "private": true,
        "publisher": "eldiron",
        "engines": { "vscode": "^1.85.0" },
        "categories": ["Programming Languages"],
        "contributes": {
            "languages": [{
                "id": definition.language_id,
                "aliases": [definition.name, "Recipe"],
                "extensions": definition.extensions.iter().map(|extension| format!(".{extension}")).collect::<Vec<_>>(),
                "configuration": "./language-configuration.json"
            }],
            "grammars": [{
                "language": definition.language_id,
                "scopeName": definition.scope,
                "path": "./syntaxes/eldiron-recipe.tmLanguage.json"
            }]
        }
    }))
}

fn generate_vscode_configuration(definition: &LanguageDefinition) -> Result<String, String> {
    pretty_json(json!({
        "$generated": GENERATED_NOTICE,
        "comments": { "lineComment": definition.line_comment },
        "brackets": [["(", ")"]],
        "autoClosingPairs": [
            { "open": "\"", "close": "\"", "notIn": ["string", "comment"] },
            { "open": "(", "close": ")" }
        ],
        "surroundingPairs": [["\"", "\""], ["(", ")"]],
        "indentationRules": {
            "increaseIndentPattern": "^\\s*(?:[A-Z][A-Za-z0-9_]*)(?:\\s+[A-Za-z_][A-Za-z0-9_-]*)?\\s*$",
            "decreaseIndentPattern": "^$"
        }
    }))
}

fn generate_tree_sitter_grammar(definition: &LanguageDefinition) -> String {
    let declarations = definition
        .declarations
        .iter()
        .map(|word| format!("\"{word}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let booleans = definition
        .booleans
        .iter()
        .map(|word| format!("\"{word}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let line_comment = serde_json::to_string(&definition.line_comment)
        .expect("a TOML string must serialize as JSON");
    format!(
        "// {GENERATED_NOTICE}\nmodule.exports = grammar({{\n  name: \"eldiron_recipe\",\n  extras: ($) => [/[ \\t]/],\n  word: ($) => $.identifier,\n  rules: {{\n    source_file: ($) => repeat(choice($.declaration, $.assignment, $.block, $.comment, $._newline)),\n    declaration: ($) => seq(field(\"kind\", choice({declarations})), optional(field(\"name\", $.identifier)), optional($.comment), optional($._newline)),\n    assignment: ($) => seq(field(\"name\", $.property), \"=\", field(\"value\", $.expression), optional($.comment), optional($._newline)),\n    block: ($) => seq(field(\"kind\", $.block_kind), optional(field(\"name\", $.identifier)), optional($.comment), optional($._newline)),\n    expression: ($) => prec.left(seq($._primary, repeat(seq($.operator, $._primary)))),\n    _primary: ($) => choice($.call, $.member, $.string, $.color, $.number, $.boolean, $.identifier, $.parenthesized_expression),\n    parenthesized_expression: ($) => seq(\"(\", $.expression, \")\"),\n    call: ($) => seq(field(\"function\", $.identifier), \"(\", optional(seq($.expression, repeat(seq(\",\", $.expression)))), \")\"),\n    member: ($) => prec.left(seq(field(\"object\", $.identifier), repeat1(seq(\".\", field(\"property\", $.identifier))))),\n    comment: ($) => token(seq({line_comment}, /.*/)),\n    string: ($) => token(seq(\"\\\"\", repeat(choice(/[^\"\\\\\\n]/, /\\\\./)), \"\\\"\")),\n    color: ($) => token(/#[0-9A-Fa-f]{{6}}([0-9A-Fa-f]{{2}})?/),\n    number: ($) => token(/-?([0-9]+(\\.[0-9]+)?|\\.[0-9]+)([eE][+-]?[0-9]+)?/),\n    boolean: ($) => choice({booleans}),\n    property: ($) => /[a-z_][a-z0-9_]*/,\n    block_kind: ($) => /[A-Z][A-Za-z0-9_]*/,\n    identifier: ($) => /[A-Za-z_][A-Za-z0-9_-]*/,\n    operator: ($) => choice(\"==\", \"!=\", \"<=\", \">=\", \"+\", \"-\", \"*\", \"/\", \"<\", \">\"),\n    _newline: ($) => /\\r?\\n/,\n  }},\n}});\n"
    )
}

fn generate_tree_sitter_package(definition: &LanguageDefinition) -> Result<String, String> {
    pretty_json(json!({
        "$generated": GENERATED_NOTICE,
        "name": "tree-sitter-eldiron-recipe",
        "version": "0.0.1",
        "private": true,
        "description": format!("Unpublished Tree-sitter grammar scaffold for {}", definition.name),
        "main": "bindings/node",
        "keywords": ["tree-sitter", "eldiron", "recipe"],
        "license": "MIT",
        "dependencies": { "node-addon-api": "^8.0.0", "node-gyp-build": "^4.8.0" },
        "devDependencies": { "tree-sitter-cli": "^0.25.0" },
        "tree-sitter": [{ "scope": definition.scope, "file-types": definition.extensions }]
    }))
}

fn generate_tree_sitter_highlights() -> String {
    format!(
        "; {GENERATED_NOTICE}\n(comment) @comment\n(string) @string\n(color) @string.special\n(number) @number\n(boolean) @boolean\n(declaration kind: (_) @keyword)\n(declaration name: (identifier) @type)\n(block kind: (block_kind) @keyword)\n(block name: (identifier) @variable)\n(assignment name: (property) @property)\n(call function: (identifier) @function)\n(member property: (identifier) @property)\n((identifier) @constant (#match? @constant \"^[A-Z]\"))\n(operator) @operator\n[\"(\" \")\" \",\" \".\"] @punctuation.bracket\n"
    )
}

fn generate_zed_configuration(definition: &LanguageDefinition) -> String {
    format!(
        "# {GENERATED_NOTICE}\nname = \"{}\"\ngrammar = \"eldiron_recipe\"\npath_suffixes = [{}]\nline_comments = [\"{} \" ]\ntab_size = 2\nhard_tabs = false\n",
        definition.name,
        definition
            .extensions
            .iter()
            .map(|extension| format!("\"{extension}\""))
            .collect::<Vec<_>>()
            .join(", "),
        definition.line_comment,
    )
}

fn pretty_json(value: serde_json::Value) -> Result<String, String> {
    serde_json::to_string_pretty(&value)
        .map(|json| format!("{json}\n"))
        .map_err(|error| error.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn definition() -> LanguageDefinition {
        toml::from_str(include_str!(
            "../../crates/procedural_recipes/language/highlighting.toml"
        ))
        .unwrap()
    }

    #[test]
    fn every_target_is_generated_from_the_same_declarations() {
        let definition = definition();
        let artifacts = generate_artifacts(&definition).unwrap();
        for declaration in &definition.declarations {
            for artifact in &artifacts {
                if artifact.path.ends_with("language-configuration.json")
                    || artifact.path.ends_with("config.toml")
                    || artifact.path.ends_with("highlights.scm")
                    || artifact.path.ends_with("package.json")
                {
                    continue;
                }
                assert!(
                    artifact.contents.contains(declaration),
                    "{} is missing {declaration}",
                    artifact.path
                );
            }
        }
    }

    #[test]
    fn generated_zed_configuration_is_valid_toml() {
        toml::from_str::<toml::Value>(&generate_zed_configuration(&definition())).unwrap();
    }
}
