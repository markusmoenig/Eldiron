use serde::Deserialize;
use serde_json::json;
use std::{
    env, fs,
    path::{Path, PathBuf},
};

const GENERATED_NOTICE: &str = "Generated by `cargo xtask recipe-language`; do not edit.";

#[derive(Debug, Deserialize)]
struct LanguageDefinition {
    name: String,
    language_id: String,
    scope: String,
    extensions: Vec<String>,
    line_comment: String,
    declarations: Vec<String>,
    booleans: Vec<String>,
}

struct Artifact {
    path: &'static str,
    contents: String,
}

fn main() {
    if let Err(error) = run() {
        eprintln!("error: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let mut arguments = env::args().skip(1);
    let Some(command) = arguments.next() else {
        return Err("usage: cargo xtask recipe-language [--check]".into());
    };
    if command != "recipe-language" {
        return Err(format!("unknown xtask '{command}'"));
    }
    let check = match arguments.next().as_deref() {
        None => false,
        Some("--check") => true,
        Some(argument) => return Err(format!("unknown argument '{argument}'")),
    };
    if let Some(argument) = arguments.next() {
        return Err(format!("unexpected argument '{argument}'"));
    }

    let root = workspace_root();
    let source_path = root.join("crates/procedural_recipes/language/highlighting.toml");
    let source = fs::read_to_string(&source_path)
        .map_err(|error| format!("cannot read '{}': {error}", source_path.display()))?;
    let definition: LanguageDefinition = toml::from_str(&source)
        .map_err(|error| format!("invalid '{}': {error}", source_path.display()))?;
    validate_definition(&definition)?;

    let artifacts = generate_artifacts(&definition)?;
    let mut stale = Vec::new();
    for artifact in artifacts {
        let path = root.join(artifact.path);
        if check {
            if fs::read_to_string(&path).ok().as_deref() != Some(&artifact.contents) {
                stale.push(artifact.path);
            }
        } else {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent)
                    .map_err(|error| format!("cannot create '{}': {error}", parent.display()))?;
            }
            fs::write(&path, artifact.contents)
                .map_err(|error| format!("cannot write '{}': {error}", path.display()))?;
            println!("generated {}", artifact.path);
        }
    }

    if stale.is_empty() {
        if check {
            println!("Recipe language artifacts are current");
        }
        Ok(())
    } else {
        Err(format!(
            "generated Recipe language artifacts are stale:\n  {}\nrun `cargo xtask recipe-language`",
            stale.join("\n  ")
        ))
    }
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask must live directly under the workspace root")
        .to_path_buf()
}

fn validate_definition(definition: &LanguageDefinition) -> Result<(), String> {
    if definition.declarations.is_empty() {
        return Err("Recipe highlighting needs at least one declaration".into());
    }
    if definition.extensions.is_empty() {
        return Err("Recipe highlighting needs at least one extension".into());
    }
    for word in definition.declarations.iter().chain(&definition.booleans) {
        if !word
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || character == '_')
        {
            return Err(format!("'{word}' is not a safe highlighting word"));
        }
    }
    Ok(())
}

fn generate_artifacts(definition: &LanguageDefinition) -> Result<Vec<Artifact>, String> {
    Ok(vec![
        Artifact {
            path: "creator/embedded/parser/recipe.sublime-syntax",
            contents: generate_sublime(definition),
        },
        Artifact {
            path: "docs/src/prism-recipe.js",
            contents: generate_prism(definition),
        },
        Artifact {
            path: "editors/vscode-eldiron-recipe/syntaxes/eldiron-recipe.tmLanguage.json",
            contents: generate_textmate(definition)?,
        },
        Artifact {
            path: "editors/vscode-eldiron-recipe/package.json",
            contents: generate_vscode_package(definition)?,
        },
        Artifact {
            path: "editors/vscode-eldiron-recipe/language-configuration.json",
            contents: generate_vscode_configuration(definition)?,
        },
        Artifact {
            path: "editors/tree-sitter-eldiron-recipe/grammar.js",
            contents: generate_tree_sitter_grammar(definition),
        },
        Artifact {
            path: "editors/tree-sitter-eldiron-recipe/package.json",
            contents: generate_tree_sitter_package(definition)?,
        },
        Artifact {
            path: "editors/tree-sitter-eldiron-recipe/queries/highlights.scm",
            contents: generate_tree_sitter_highlights(),
        },
        Artifact {
            path: "editors/zed-eldiron-recipe/languages/eldiron-recipe/config.toml",
            contents: generate_zed_configuration(definition),
        },
        Artifact {
            path: "editors/zed-eldiron-recipe/languages/eldiron-recipe/highlights.scm",
            contents: generate_tree_sitter_highlights(),
        },
    ])
}

fn alternatives(words: &[String]) -> String {
    let mut words = words.to_vec();
    words.sort_by_key(|word| std::cmp::Reverse(word.len()));
    words.join("|")
}

fn regex_escape(text: &str) -> String {
    text.chars()
        .flat_map(|character| {
            if "\\.^$|?*+()[]{}".contains(character) {
                vec!['\\', character]
            } else {
                vec![character]
            }
        })
        .collect()
}

fn generate_sublime(definition: &LanguageDefinition) -> String {
    let declarations = alternatives(&definition.declarations);
    let booleans = alternatives(&definition.booleans);
    let comment = regex_escape(&definition.line_comment);
    format!(
        "%YAML 1.2\n---\n# {GENERATED_NOTICE}\nname: {}\nfile_extensions:\n{}scope: {}\n\ncontexts:\n  main:\n    - match: '{comment}.*$'\n      scope: comment.line.double-slash.eldiron-recipe\n    - match: '\"'\n      scope: punctuation.definition.string.begin.eldiron-recipe\n      push:\n        - meta_scope: string.quoted.double.eldiron-recipe\n        - match: '\"'\n          scope: punctuation.definition.string.end.eldiron-recipe\n          pop: true\n        - match: '\\\\.'\n          scope: constant.character.escape.eldiron-recipe\n    - match: '#[0-9A-Fa-f]{{6}}(?:[0-9A-Fa-f]{{2}})?\\b'\n      scope: constant.other.color.eldiron-recipe\n    - match: '^\\s*({declarations})\\b(?:\\s+([A-Za-z_][A-Za-z0-9_-]*))?'\n      captures:\n        1: keyword.declaration.eldiron-recipe\n        2: entity.name.type.eldiron-recipe\n    - match: '^\\s*([A-Z][A-Za-z0-9_]*)(?:\\s+([A-Za-z_][A-Za-z0-9_-]*))?(?=\\s*(?:{comment}.*)?$)'\n      captures:\n        1: support.type.block.eldiron-recipe\n        2: entity.name.label.eldiron-recipe\n    - match: '^\\s*([a-z_][a-z0-9_]*)\\s*(=)'\n      captures:\n        1: variable.other.property.eldiron-recipe\n        2: keyword.operator.assignment.eldiron-recipe\n    - match: '\\b[A-Z][A-Za-z0-9_]*(?=\\s*\\()'\n      scope: support.function.eldiron-recipe\n    - match: '\\b(?:{booleans})\\b'\n      scope: constant.language.eldiron-recipe\n    - match: '-?(?:\\b\\d+(?:\\.\\d+)?|\\.\\d+)(?:[eE][+-]?\\d+)?\\b'\n      scope: constant.numeric.eldiron-recipe\n    - match: '(?<=\\.)[A-Za-z_][A-Za-z0-9_]*\\b'\n      scope: variable.other.member.eldiron-recipe\n    - match: '\\b[A-Z][A-Za-z0-9_]*\\b'\n      scope: constant.other.eldiron-recipe\n    - match: '==|!=|<=|>=|[=+\\-*/<>]'\n      scope: keyword.operator.eldiron-recipe\n    - match: '[(),.]'\n      scope: punctuation.eldiron-recipe\n",
        definition.name,
        definition
            .extensions
            .iter()
            .map(|extension| format!("  - {extension}\n"))
            .collect::<String>(),
        definition.scope,
    )
}

fn generate_prism(definition: &LanguageDefinition) -> String {
    let declarations = alternatives(&definition.declarations);
    let booleans = alternatives(&definition.booleans);
    let comment = regex_escape(&definition.line_comment).replace('/', "\\/");
    format!(
        "// {GENERATED_NOTICE}\nexport default function loadRecipe(Prism) {{\n  Prism.languages[\"{}\"] = {{\n    comment: {{ pattern: /{comment}.*/, greedy: true }},\n    string: {{ pattern: /\"(?:\\\\.|[^\"\\\\])*\"/, greedy: true }},\n    color: {{ pattern: /#[0-9A-Fa-f]{{6}}(?:[0-9A-Fa-f]{{2}})?\\b/, alias: \"constant\" }},\n    declaration: {{\n      pattern: /(^\\s*)(?:{declarations})(?=\\s|$)/m,\n      lookbehind: true,\n      alias: \"keyword\",\n    }},\n    block: {{\n      pattern: /(^\\s*)[A-Z][A-Za-z0-9_]*(?=(?:\\s+[A-Za-z_][A-Za-z0-9_-]*)?\\s*(?:{comment}.*)?$)/m,\n      lookbehind: true,\n      alias: \"class-name\",\n    }},\n    property: {{\n      pattern: /(^\\s*)[a-z_][a-z0-9_]*(?=\\s*=)/m,\n      lookbehind: true,\n    }},\n    function: /\\b[A-Z][A-Za-z0-9_]*(?=\\s*\\()/,\n    boolean: {{ pattern: /\\b(?:{booleans})\\b/, alias: \"constant\" }},\n    number: /-?(?:\\b\\d+(?:\\.\\d+)?|\\.\\d+)(?:[eE][+-]?\\d+)?\\b/,\n    member: {{ pattern: /(\\.)[A-Za-z_][A-Za-z0-9_]*/, lookbehind: true, alias: \"property\" }},\n    constant: /\\b[A-Z][A-Za-z0-9_]*\\b/,\n    operator: /==|!=|<=|>=|[=+\\-*/<>]/,\n    punctuation: /[(),.]/,\n  }};\n  Prism.languages.recipe = Prism.languages[\"{}\"];\n}}\n",
        definition.language_id, definition.language_id,
    )
}

